"""Icons referenced by components have to exist as partials.

The partials are generated by scripts/generate_icons.py, which needs network
access. These checks are offline: they only compare what the markup asks for
against what is on disk.
"""

import importlib.util
import re
from pathlib import Path

import pytest

ICON_USAGE = re.compile(r'<c-icon\s[^>]*name=[\'"]([a-z0-9-]+)[\'"]')

# Shipped as the component itself, not as an icon.
NOT_AN_ICON = {'index.html'}


def icons_referenced(components_root) -> set[str]:
    names: set[str] = set()

    for template in components_root.rglob('*.html'):
        names.update(ICON_USAGE.findall(template.read_text(encoding='utf-8')))

    return names


def icons_available(components_root) -> set[str]:
    return {
        path.stem.replace('_', '-')
        for path in (components_root / 'icon').glob('*.html')
        if path.name not in NOT_AN_ICON
    }


def test_components_reference_icons(components_root):
    assert icons_referenced(components_root), 'no <c-icon> usage found'


def test_every_referenced_icon_has_a_partial(components_root):
    missing = icons_referenced(components_root) - icons_available(
        components_root
    )

    assert not missing, (
        f'missing icon partials: {sorted(missing)}. '
        'Run python scripts/generate_icons.py'
    )


def test_no_unused_icon_partials(components_root):
    unused = icons_available(components_root) - icons_referenced(
        components_root
    )

    assert not unused, f'icons nothing references: {sorted(unused)}'


def test_no_inline_svg_outside_the_icon_component(components_root):
    """Icons come from lucide through <c-icon>, never pasted by hand.

    `chart` draws with SVG rather than decorating with it: its elements are
    empty surfaces that Alpine fills with computed geometry, and there is no
    lucide shape in them to drift out of date.
    """
    drawn = {'chart'}

    offenders = [
        path.relative_to(components_root)
        for path in components_root.rglob('*.html')
        if path.parent.name != 'icon'
        and path.parent.name not in drawn
        and '<svg' in path.read_text(encoding='utf-8')
    ]

    assert not offenders, f'inline svg found in: {offenders}'


def _generator():
    path = Path(__file__).resolve().parent.parent / 'scripts'
    spec = importlib.util.spec_from_file_location(
        'generate_icons', path / 'generate_icons.py'
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_every_shipped_partial_is_only_shapes(components_root):
    """What the generator refuses to write must not be on disk either."""
    unsafe_shapes = _generator().unsafe_shapes
    offenders = {}

    for path in (components_root / 'icon').glob('*.html'):
        if path.name in NOT_AN_ICON:
            continue
        lines = path.read_text(encoding='utf-8').splitlines()
        if unsafe_shapes(lines):
            offenders[path.name] = unsafe_shapes(lines)

    assert not offenders, offenders


@pytest.mark.parametrize(
    'line',
    [
        '<script>alert(1)</script>',
        '<path d="M0 0" onload="alert(1)" />',
        '<path d="{% debug %}" />',
        '<path d="{{ request }}" />',
        '<image href="https://example.com/x.png" />',
        '<path d="M0 0" style="fill:url(#x)" />',
        '<path d="M0 0"/><script/>',
        '<a href="javascript:alert(1)"><path d="M0 0" /></a>',
    ],
)
def test_the_generator_refuses_anything_but_shapes(line):
    assert _generator().unsafe_shapes([line]) == [line]


def test_the_generator_accepts_lucide_shapes():
    shapes = [
        '<path d="M20 6 9 17l-5-5" />',
        '<circle cx="12" cy="12" r="10" />',
        '<rect width="18" height="18" x="3" y="3" rx="2" />',
    ]

    assert _generator().unsafe_shapes(shapes) == []
